function M.get_candidates(syllable)
    if not syllable or syllable == "" then return {} end
    local s = string.lower(syllable)
    local str = DICT[s]
    if not str then return {} end
    local res = {}
    local p = 1
    local len = #str
    while p <= len do
        local b = string.byte(str, p)
        local char_len = 1
        if b >= 240 then char_len = 4
        elseif b >= 224 then char_len = 3
        elseif b >= 192 then char_len = 2
        end
        table.insert(res, string.sub(str, p, p + char_len - 1))
        p = p + char_len
    end
    return res
end

return M
